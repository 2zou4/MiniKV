namespace minikv {

// ──────────────────────────────────────────────
// LookupResult：三态查询结果
// ──────────────────────────────────────────────
//
// 为什么不能只用 bool（存在/不存在）？
//
// 在单个数据源（比如一个独立的 SkipList 或一个已经完全合并过的
// 底层 SSTable）里，"存在但被删除"和"从未存在过"最终效果一样，
// 用 bool 表示"查不到"完全够用。
//
// 但一旦要跨多个数据源、按新旧顺序查找（MemTable → L0 新到旧 → L1），
// 这两种情况必须区分开：
//   - 如果最新的数据源里这个 key 是"从未出现过"，应该继续去更旧的
//     数据源里找，因为它可能存在于更早写入的地方。
//   - 如果最新的数据源里这个 key 是"tombstone"（明确被删除过），
//     必须立刻停止查找，返回"不存在"——不能因为更旧的数据源里
//     还留着这个 key 的旧值，就误把它当成有效数据返回，
//     那样已经删除的数据会诡异地"复活"。
//
// 这是 LSM-Tree 多层查询正确性的核心细节。

enum class LookupResult {
    kFound,      // 找到有效值
    kDeleted,    // 找到了，但是被标记删除（tombstone），查找应该在此停止
    kNotFound,   // 这个数据源里完全没有这个 key 的任何记录，可以继续往更旧的层找
};

}  // namespace minikv